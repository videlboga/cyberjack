CACHE = ROOT / "eventLibrary.cache.json"
OLLAMA_URL = "http://127.0.0.1:11434/api/generate"
MODEL = "gemma4:cloud"

FORBIDDEN_RE = re.compile(
    r"\b(умер[а-я]*|погиб[а-я]*|убил[а-я]*|убийств[а-я]*|родител|сестр[а-я]*|брат[а-я]*|дочь|сын|муж|жен[а-я]|смерть|виноват|природа Аномалии|природу Аномалии|зачистк[а-я]*)\b",
    re.IGNORECASE,
)

# ─────────────────────────────────────────────────────────────────────────────
# Helpers
# ─────────────────────────────────────────────────────────────────────────────

def _clean(t: Any) -> str:
    t = str(t).strip()
    t = re.sub(r"^\s*[-*•]\s+", "", t, flags=re.MULTILINE)
    t = re.sub(r"\*\*", "", t)
    t = re.sub(r"\s+", " ", t)
    t = re.sub(r"^\d+[.)]\s*", "", t)
    return t.strip()


def _llm(prompt: str, max_tokens: int = 1024, temperature: float = 0.35) -> str:
    payload = {
        "model": MODEL,
        "prompt": prompt,
        "stream": False,
        "options": {"temperature": temperature, "num_predict": max_tokens},
    }
    req = urllib.request.Request(
        OLLAMA_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            return _clean(data.get("response", ""))
    except Exception as e:
        print(f"[llm error] {e}", file=sys.stderr)
        return ""


class Cache:
    def __init__(self):
        self._data: dict[str, Any] = {}
        if CACHE.exists():
            try:
                self._data = json.loads(CACHE.read_text(encoding="utf-8"))
            except Exception:
                self._data = {}

    def get(self, key: str) -> Any | None:
        return self._data.get(key)

    def set(self, key: str, value: Any) -> None:
        self._data[key] = value
        CACHE.write_text(json.dumps(self._data, ensure_ascii=False, indent=2), encoding="utf-8")


CACHE_OBJ = Cache()


def safe_text(t: str, fallback: str) -> str:
    t = _clean(t)
    if not t or FORBIDDEN_RE.search(t):
        return fallback
    return t


def cached_call(key: str, fn: Any, *args: Any, **kwargs: Any) -> Any:
    value = CACHE_OBJ.get(key)
    if value is not None:
        return value
    value = fn(*args, **kwargs)
    CACHE_OBJ.set(key, value)
    return value


