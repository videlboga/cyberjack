def _parse_faction_contracts(text: str, faction: str, asset_types: list[str]) -> list[dict[str, Any]]:
    # Try to extract JSON array/object from the response first.
    text = text.strip()
    # If model wrapped in markdown code fence
    if "```" in text:
        m = re.search(r"```(?:json)?\s*([\s\S]*?)```", text)
        if m:
            text = m.group(1).strip()
    try:
        parsed_json = json.loads(text)
        if isinstance(parsed_json, list):
            items = parsed_json
        elif isinstance(parsed_json, dict):
            # may be keyed by asset type
            items = [parsed_json.get(at) for at in asset_types if parsed_json.get(at)]
            if not items:
                items = [parsed_json]
        else:
            items = []
    except Exception:
        items = []
    results: list[dict[str, Any]] = []
    for idx, asset_type in enumerate(asset_types):
        if idx < len(items) and isinstance(items[idx], dict):
            item = items[idx]
        else:
            item = {}
        narrative_reason = safe_text(item.get("narrativeReason", item.get("narrative_reason", "")), "фракция заинтересована в активе")
        faction_interest = safe_text(item.get("factionInterest", item.get("faction_interest", "")), "пополнить пул объектов")
        mechanical = item.get("mechanicalConditions", item.get("mechanical_conditions", []))
        if not isinstance(mechanical, list):
            mechanical = []
        mechanical = [safe_text(x, "attitude >= 60") for x in mechanical]
        while len(mechanical) < 2:
            mechanical.append("attitude >= 60")
        results.append({
            "id": f"contract_{faction.replace('fac_', '')}_{asset_type}_{idx + 1:02d}",
            "factionId": faction,
            "assetType": asset_type,
            "narrativeReason": narrative_reason,
            "factionInterest": faction_interest,
            "mechanicalConditions": mechanical[:4],
            "reward": safe_text(item.get("reward", ""), "credits + trust"),
            "complication": safe_text(item.get("complication", ""), "контракт может привлечь внимание конкурентов"),
            "offerMessage": safe_text(item.get("offerMessage", item.get("offer_message", "")), "поступило предложение"),
            "acceptMessage": safe_text(item.get("acceptMessage", item.get("accept_message", "")), "условия приняты"),
            "successOutcome": safe_text(item.get("successOutcome", item.get("success_outcome", "")), "контракт выполнен"),
            "failureOutcome": safe_text(item.get("failureOutcome", item.get("failure_outcome", "")), "контракт истёк или провален"),
            "futurePlotThread": safe_text(item.get("futurePlotThread", item.get("future_plot_thread", "")), "фракция может обратиться снова"),
        })
    return results


