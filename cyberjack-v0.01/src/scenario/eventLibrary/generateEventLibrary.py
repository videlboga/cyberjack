"""Генератор библиотеки нарративного контента для cyberjack v0.01.

Подход:
- Персонажные последовательности, контракты, цепочки снабжения, LLM-пакеты
  генерируются через LLM (gemma4:cloud) по одному сложному блоку за вызов.
- Короткие события, повторяющиеся персонажи, эпизодические архетипы,
  станционные события, фоновые наблюдения, шаблоны эхо формируются
  из расширенных ручных шаблонов: это гарантирует формат и качество.
"""

import json
