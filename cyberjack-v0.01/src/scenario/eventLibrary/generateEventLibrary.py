def validate_library(library: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    expected = {
        "shortEvents": 40, "characterSequences": 8, "recurringCharacters": 8,
        "episodicArchetypes": 12, "factionContracts": 18, "supplyChains": 12,
        "stationEvents": 24, "backgroundObservations": 30, "echoTemplates": 20, "llmPromptPacks": 10,
    }
    for key, count in expected.items():
        actual = len(library.get(key, []))
        if actual != count:
            errors.append(f"{key}: expected {count}, got {actual}")
    for seq in library.get("characterSequences", []):
        if len(seq.get("events", [])) != 6:
            errors.append(f"characterSequences {seq.get('characterId')}: expected 6 events, got {len(seq.get('events', []))}")
        # nested events do not need an id; characterId is the unique identifier
    return errors


