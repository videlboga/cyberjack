/**
 * Авторские профили персонажей в коде.
 *
 * Каждый профиль собирается цепочкой «личная история → сценарий жизни (ТА) →
 * параметры → знания мира (loreRefs)». Внешних несуществующих персонажей нет:
 * личная история ссылается только на семью и организации мира (Veil Biotech,
 * Helix Dynamics, Continuum Archive, Lattice Systems, Культ).
 *
 * `compileAuthoredProfile` возвращает GeneratedProfileV2, который движок
 * (`ensureGeneratedProfile`) отдаёт ПЕРЕД LLM-генерацией, поэтому все поля
 * (параметры, lore, история, социальная ТА-модель) контролируются здесь.
 */

interface TAModel {
  script: string;                    // сценарий жизни по Берну
  egoState: string;                  // скриптовое эго-состояние
  lifePosition: string;              // жизненная позиция
  stressNeeds: string[];             // потребности
  conversationHooks: string[];       // крючки тем
  hookContexts?: Record<string, string>; // контекст каждого крючка (тема → что она значит)
  racket: string;                    // рэкет-чувство
  game: string;                      // любимая Игра
  final: string;                     // сценарий-финал
  antiScript: string;                // антисценарий (точка роста)
}

interface AuthoredProfile {
  identity: {
    name: string;
    age: number;
    gender: 'male' | 'female' | 'other';
    coreSummary: string;
    origin: string;
    socialBackground: string;
    formerRole: string;
  };
  biography: {
    summary: string;
    formativeEvents: string[];
  };
  psychology: {
    values: string[];
    consciousDesires: string[];
    unacknowledgedDesires: string[];
    fears: string[];
    vulnerabilities: string[];
    contradictions: string[];
    defenses: string[];
  };
  voice: {
    description: string;
    rhythm: string;
    emotionalModes: Record<string, string>;
  };
  behavior: {
    mannerisms: string[];
  };
  appearance: {
    description: string;
    presentation: string;
  };
  /** Параметры персонажа: coreModifiers относительно 50. */
  coreModifiers: Record<string, number>;
  /** Знания о мире (uid лор-записей). Разный уровень знания у разных персонажей. */
  loreRefs: string[];
  /** ТА-модель: сценарий жизни + социальные поля. */
  ta: TAModel;
}

