const compact = (values: unknown[] = [], limit = 6) =>
  Array.from(new Set(values.map(String).map((value) => value.trim()).filter(Boolean))).slice(0, limit);

export function getAuthoredProfile(subjectId: string): AuthoredProfile | undefined {
  return profiles[subjectId];
}

export function compileAuthoredProfile(
  subjectId: string,
  currentRole: string | undefined,
  roleState?: Record<string, any>,
): GeneratedProfileV2 | undefined {
  const source = getAuthoredProfile(subjectId);
  if (!source) return undefined;
  const identity = source.identity;
  const psychology = source.psychology;
  const voice = source.voice;
  const biography = source.biography;
  const rawRole = currentRole || 'person';
  const role = rawRole === 'assistant' ? 'staff' : rawRole;
  const archetype: CharacterArchetype = role === 'asset' ? 'asset' : 'person';

  const ta = source.ta;
  const dynamicsText =
    '[Как применять профиль]\nЭто устойчивые склонности, биография и сценарий жизни, а не описание текущей эмоции. Текущее состояние, отношение, доверие, готовность, возбуждение и реакция на воздействие определяются данными ядра и отношениями в актуальном контексте. Не изображай страх, покорность, возбуждение, согласие или привязанность только потому, что они упомянуты в профиле.';

  const personaText = [
    `[Личность]\n${identity.coreSummary}`,
    `[Биография]\n${biography.summary}`,
    `[Внешность]\n${source.appearance.description} ${source.appearance.presentation}`,
    `[Манера речи]\n${voice.description}\n${voice.rhythm}`,
    `[Текущее положение]\nРоль: ${role}.`,
    `[Сценарий жизни]\n${ta.script}. Позиция: ${ta.lifePosition}. Потребности: ${ta.stressNeeds.join(', ')}. Рэкет-чувство: ${ta.racket}. Антисценарий: ${ta.antiScript}.`,
    dynamicsText,
    `[Инструкции] Ответь ТОЛЬКО прямой речью персонажа, от первого лица, без JSON, служебных полей, звёздочек, кавычек-ремарок и БЕЗ описаний действий, жестов, мимики, пауз и внутренних комментариев (не пиши «я замолкаю», «подбирая слова», «улыбаюсь», «киваю» и т.п.). Твоя реплика — это только произносимые слова.`,
  ].join('\n\n');

  return {
    version: 2,
    generatorRevision: Number.MAX_SAFE_INTEGER,
    subjectId,
    seed: `authored:${subjectId}`,
    authored: true,
    authoredProfile: source as any,
    identity: {
      name: identity.name,
      age: identity.age,
      gender: identity.gender,
      anatomy: 'human',
      archetype,
    },
    biography: {
      origin: compact([identity.origin, identity.socialBackground], 3),
      formerRole: identity.formerRole,
      statusCause: undefined,
      formativeEvents: compact(biography.formativeEvents, 5),
    },
    behavioralCore: {
      values: compact(psychology.values, 5),
      needs: compact(psychology.unacknowledgedDesires, 3),
      vulnerabilities: compact(psychology.vulnerabilities, 4),
      defenses: compact(psychology.defenses, 4),
      voice: compact([voice.description, voice.rhythm], 2),
      emotionalVoice: voice.emotionalModes || {},
      mannerisms: compact(source.behavior.mannerisms, 4),
      centralConflict: {
        desire: psychology.consciousDesires?.[0] || 'сохранить право определять собственную жизнь',
        fear: psychology.fears?.[0] || 'потерять контроль над происходящим',
      },
      attentionFocus: ['person', 'rules', 'change'],
      speechDisposition: 'expressive',
      conditionalReactions: [],
    },
    knowledgeRefs: source.loreRefs,
    mechanicalSeed: {
      coreModifiers: source.coreModifiers || {},
      initialContexts: [],
      preferences: { actions: {}, points: {}, contexts: {}, tags: {} },
    },
    sourceTags: [],
    loreRefs: source.loreRefs,
    personaText,
    personaWithoutTraits: personaText,
    traitBlock: compact([...psychology.values, ...psychology.contradictions], 7).join('\n'),
    identityText: `${identity.name}, ${identity.age} лет; ${identity.origin}.`,
    historyText: biography.summary,
    activationText: '',
    systemPrompt: personaText,
    updatedAt: new Date().toISOString(),
  };
}


/**
 * Применяет социальную ТА-модель (эго, позиция, потребности, крючки) из
 * авторского профиля в profile_json.social — единый источник истины.
 * Вызывается при старте мира (ensureWorldSeed).
 */
export function applyAuthoredSocialToProfiles(): string[] {
    const applied: string[] = [];
    for (const [subjectId, source] of Object.entries(profiles)) {
        const row = db.prepare('SELECT profile_json FROM characters WHERE id = ? OR subject_id = ? LIMIT 1').get(subjectId, subjectId) as any;
        if (!row) continue;
        const profileJson = JSON.parse(row.profile_json || '{}');
        const social = {
            defaultEgoState: source.ta.egoState,
            lifePosition: source.ta.lifePosition,
            stressNeeds: source.ta.stressNeeds,
            conversationHooks: source.ta.conversationHooks,
            hookContexts: source.ta.hookContexts || {},
            script: source.ta.script,
            racket: source.ta.racket,
            game: source.ta.game,
            final: source.ta.final,
            antiScript: source.ta.antiScript,
        };
        profileJson.social = social;
        db.prepare('UPDATE characters SET profile_json = ? WHERE id = ?').run(JSON.stringify(profileJson), subjectId);
        applied.push(subjectId);
    }
    return applied;
}
