const byBundle = new Map();
for (const [mode, id, ja, posture, categories, female, male] of HSCENE_ROWS) {
  for (const key of [female, male]) {
    if (!key) continue;
    if (!byBundle.has(key)) byBundle.set(key, []);
    byBundle.get(key).push({mode, id, ja, posture, categories, female, male});
  }
}
export function hsceneBundleKey(entry) {
  const m = /^h\/anim\/(?:female|male)\/(\d\d_\d\d_\d\d)\.unity3d$/.exec(String(entry || '').replace(/^abdata\//, ''));
  return m ? m[1] : null;
}
export function hsceneFor(entry) {
  const key = hsceneBundleKey(entry);
  if (!key) return null;
  const rows = byBundle.get(key);
  if (!rows) return null;
  const modes = [...new Set(rows.map((r) => r.mode))].sort((a, b) => a - b);
  const positions = [];
  for (const r of rows) {
    if (positions.some((p) => p.mode === r.mode && p.id === r.id)) continue;
    positions.push({mode: r.mode, id: r.id, ja: r.ja, posture: r.posture, categories: r.categories});
  }
  return {bundle: key, modes, modeLabels: modes.map((m) => m + ': ' + (H_MODES[m] || 'режим')), positions, postureCodes: [...new Set(rows.map((r) => r.posture))], partnerBundle: rows.find((r) => r.male)?.male || null};
}
