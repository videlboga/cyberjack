async function call(system: string, user: string) {
    const resp = await fetch('https://openrouter.ai/api/v1/chat/completions', {
        method: 'POST',
        headers: {
            'Content-Type': 'application/json',
            'Authorization': `Bearer ${process.env.OPENROUTER_API_KEY}`,
            'HTTP-Referer': 'http://localhost:3000', 'X-Title': 'ta-formulation-batch',
        },
        body: JSON.stringify({
            model: process.env.LLM_MODEL || 'deepseek/deepseek-v4-flash',
            messages: [{ role: 'system', content: system }, { role: 'user', content: user }],
            stream: false, max_tokens: 120, temperature: 0.85, top_p: 0.9,
            reasoning: { enabled: false },
        }),
    });
    if (!resp.ok) return `ERROR ${resp.status}`;
    const data = await resp.json();
    return (data.choices?.[0]?.message?.content ?? '').trim();
}

const variantKey = process.env.VARIANT_KEY || 'v1';
const scKey = process.env.SCENARIO || 'boundaries';
const sc = SCENARIOS[scKey];

for (let run = 1; run <= 3; run++) {
    const reply = await call(SYSTEM, `${sc.context}\n\n${sc[variantKey]}`);
    console.log(`RUN ${run}: ${reply}`);
}
