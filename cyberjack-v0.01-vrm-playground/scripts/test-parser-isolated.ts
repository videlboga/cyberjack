import 'dotenv/config';
import { parseSemanticVerbalInput } from '../src/parser/semanticVerbalParser';
import '../src/infrastructure/db';

const SUBJ = 'NPC-CAND-SUMI';

async function run(label: string, text: string, opts: { context?: string; dialogue?: string; lastSpeech?: string } = {}) {
    const start = performance.now();
    try {
        const result = await parseSemanticVerbalInput(
            text,
            opts.context || 'Текущее место: Жилая камера B. Персонажи рядом: Суми.',
            [{ id: SUBJ, name: 'Суми' }],
            SUBJ,
            SUBJ,
            opts.lastSpeech || '',
            'PL-1',
            null,
            opts.dialogue || '',
        );
        const ms = Math.round(performance.now() - start);
        const ci = result.commandIntent || {};
        const ciStr = ci.type === 'none' ? 'none' : ci.type === 'misunderstood' ? `misunderstood:${ci.partial}` : `${ci.type}${ci.targetPoseId ? ':' + ci.targetPoseId : ''}${ci.actionId ? ':' + ci.actionId : ''}${ci.targetContextId ? ':' + ci.targetContextId : ''}`;
        console.log(`[${ms}ms] ${label}`);
        console.log(`   text:          ${text}`);
        console.log(`   commandIntent: ${ciStr}`);
        console.log('---');
    } catch (e: any) {
        console.log(`[ERR] ${label} — ${e?.message || e}`);
        console.log('---');
    }
}

// Прогрев каталога
await parseSemanticVerbalInput('тест', '', [], SUBJ, SUBJ).catch(() => {});

// ===== РАСТЯНУТЫЙ КОНТЕКСТ: местоимения, подразумеваемые контекстом =====

