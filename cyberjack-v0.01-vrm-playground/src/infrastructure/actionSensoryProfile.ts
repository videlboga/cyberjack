import { CompiledAction } from '../domain/types';

export type SensoryProfile = NonNullable<CompiledAction['sensory']>;

export interface SensoryActionSource {
    id: string;
    name: string;
    description?: string;
    categories?: string[];
    tags?: string[];
    sensory?: SensoryProfile;
}



const firstMatch = (tags: Set<string>, variants: Array<[string[], string]>): string | undefined =>
    variants.find(([needles]) => needles.some(tag => tags.has(tag)))?.[1];

function inferredStimulus(action: SensoryActionSource, tags: Set<string>): string {
    if (action.description) return action.description;
    if (tags.has('remove')) return `${action.name}: материал перестаёт касаться тела, ранее закрытая область освобождается.`;
    if (tags.has('clothing')) return `${action.name}: ткань проходит по коже и укладывается вокруг тела.`;
    if (tags.has('comfort')) return `${action.name}: прежнее ограничение контакта исчезает.`;
    return `${action.name}: воздействие ощущается непосредственно в указанной зоне.`;
}

