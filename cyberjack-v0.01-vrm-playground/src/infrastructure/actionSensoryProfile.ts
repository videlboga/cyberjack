function inferredAftereffect(tags: Set<string>): string | undefined {
    return firstMatch(tags, [
        [['shock'], 'После разряда остаются короткая мышечная дрожь и жгучий след в месте контакта.'],
        [['impact', 'pain'], 'После главного импульса остаются тепло, пульсация или болезненная чувствительность зоны.'],
        [['remove', 'comfort', 'relief'], 'После прекращения контакта ещё различимы след давления и постепенное возвращение свободы движения.'],
        [['chemical', 'infusion'], 'Локальное ощущение введения проходит раньше, чем системное действие вещества.'],
        [['continuous'], 'После остановки тело ещё несколько мгновений ожидает следующий повтор и сохраняет эхо ритма.'],
        [['stop'], 'После выхода из контакта остаются остаточное внутреннее давление, тепло и постепенное расслабление мышц.'],
        [['exposure'], 'Даже после смены позы некоторое время сохраняется чувство открытости и внимание к ранее предъявленной области.'],
    ]);
}

export function completeActionSensoryProfile(action: SensoryActionSource): {
    description: string;
    sensory: SensoryProfile;
} {
    const tags = new Set(action.tags || []);
    const categories = new Set(action.categories || []);
    const inferred: SensoryProfile = {
        stimulus: inferredStimulus(action, tags),
        texture: inferredTexture(tags, categories),
        rhythm: inferredRhythm(tags, categories),
        bodilyResponse: inferredBodyResponse(tags, categories),
        aftereffect: inferredAftereffect(tags),
    };
    const sensory = Object.fromEntries(
        Object.entries({ ...inferred, ...(action.sensory || {}) }).filter(([, value]) => Boolean(value))
    ) as SensoryProfile;
    return {
        description: action.description || inferred.stimulus || action.name,
        sensory,
    };
}
